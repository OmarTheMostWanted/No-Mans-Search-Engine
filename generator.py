from __future__ import annotations

import random
import time
from collections.abc import Iterator, Sequence
from typing import Any, Protocol

from config import SearchConfig, galaxy_to_generator_index, normalize_portal_address
from models import SearchResult, SystemRecord


class SystemProvider(Protocol):
    def batch(self, portal_addresses: Sequence[str], galaxy: int = 0) -> list[dict[str, Any]]: ...


class SystemCache(Protocol):
    def get(self, address: str, galaxy: int) -> dict[str, Any] | None: ...
    def set(self, address: str, galaxy: int, payload: dict[str, Any]) -> None: ...


def iter_portal_addresses(config: SearchConfig) -> Iterator[str]:
    """Generate canonical system portal codes (planet glyph 0, 44-bit address space)."""
    if config.search_mode == "random":
        rng = random.Random(config.random_seed)
        while True:
            yield f"0{rng.getrandbits(44):011X}"
    else:
        number = int(normalize_portal_address(config.start_address or "000000000000"), 16) & 0xFFFFFFFFFFF
        while True:
            yield f"0{number:011X}"
            number = (number + 1) & 0xFFFFFFFFFFF


def search_systems(config: SearchConfig, provider: SystemProvider,
                   cache: SystemCache | None = None) -> list[SystemRecord]:
    """Search actual portal-code systems generated by the bundled NMS library."""
    config.validate()
    addresses = iter_portal_addresses(config)
    galaxy_index = galaxy_to_generator_index(config.galaxy)
    deadline = time.monotonic() + config.duration_seconds
    inspected = 0
    matches: list[SystemRecord] = []
    while config.max_systems is None or inspected < config.max_systems:
        if time.monotonic() >= deadline:
            break
        size = config.batch_size
        if config.max_systems is not None:
            size = min(size, config.max_systems - inspected)
        candidates = [next(addresses) for _ in range(size)]
        payloads: dict[str, dict[str, Any]] = {}
        missing = []
        for address in candidates:
            cached = cache.get(address, galaxy_index) if config.cache_enabled and cache else None
            if cached is None:
                missing.append(address)
            else:
                payloads[address] = cached
        if missing:
            fetched = provider.batch(missing, galaxy=galaxy_index)
            if len(fetched) != len(missing):
                raise RuntimeError(f"NMS generator returned {len(fetched)} systems for {len(missing)} addresses.")
            for address, payload in zip(missing, fetched):
                payloads[address] = payload
                if config.cache_enabled and cache:
                    cache.set(address, galaxy_index, payload)
        for address in candidates:
            inspected += 1
            result = SystemRecord.from_upstream(payloads[address], address, config.galaxy)
            if result.matches(config):
                matches.append(result)
                if config.max_matches is not None and len(matches) >= config.max_matches:
                    return matches
        if config.max_systems is not None and inspected >= config.max_systems:
            break
    return matches


__all__ = ["SystemRecord", "SearchResult", "search_systems", "iter_portal_addresses"]
