from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

from config import SearchConfig, normalize_portal_address


def _text(value: Any) -> str | None:
    return str(value).strip().lower() if value is not None and str(value).strip() else None


def _number(value: Any) -> int | None:
    if isinstance(value, bool) or value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _flag(value: Any) -> bool | None:
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        value = value.strip().lower()
        if value in {"true", "1", "yes"}:
            return True
        if value in {"false", "0", "no"}:
            return False
    return None


@dataclass(frozen=True)
class SystemRecord:
    """One system generated by the real nms-galactic-map submodule."""

    portal_address: str
    galaxy: int
    data: dict[str, Any]

    @classmethod
    def from_upstream(cls, data: dict[str, Any], address: str, galaxy: int) -> "SystemRecord":
        if not isinstance(data, dict):
            raise TypeError("Upstream system must be a JSON object.")
        normalized = normalize_portal_address(str(data.get("address", address)))
        if normalized != normalize_portal_address(address):
            raise ValueError(f"System address mismatch: requested {address}, received {normalized}.")
        if int(data.get("galaxy", -1)) != galaxy - 1:
            raise ValueError(f"System galaxy mismatch: expected {galaxy - 1}, got {data.get('galaxy')}.")
        required = ("starType", "planets", "moons", "race", "economy", "econTier", "conflict",
                    "conTier", "abandoned", "uncharted", "outlaw", "isBlackHole", "isAtlas", "coords")
        missing = [key for key in required if key not in data]
        if missing:
            raise ValueError(f"Upstream system data is missing: {', '.join(missing)}")
        return cls(normalized, galaxy, data)

    @property
    def star_color(self) -> str | None:
        return _text(self.data.get("starType"))

    @property
    def planets(self) -> int | None:
        return _number(self.data.get("planets"))

    @property
    def moons(self) -> int | None:
        return _number(self.data.get("moons"))

    @property
    def race(self) -> str | None:
        return _text(self.data.get("race"))

    @property
    def economy(self) -> str | None:
        return _text(self.data.get("economy"))

    @property
    def conflict(self) -> str | None:
        return _text(self.data.get("conflict"))

    @property
    def economy_tier(self) -> int | None:
        tier = _number(self.data.get("econTier"))
        return tier + 1 if tier is not None and 0 <= tier <= 2 else None

    @property
    def conflict_tier(self) -> int | None:
        tier = _number(self.data.get("conTier"))
        return tier + 1 if tier is not None and 0 <= tier <= 2 else None

    @property
    def pirate(self) -> bool | None:
        return _flag(self.data.get("outlaw"))

    @property
    def core_distance(self) -> float | None:
        coords = self.data.get("coords")
        if not isinstance(coords, dict):
            return None
        try:
            x, y, z = (float(coords[axis]) for axis in ("x", "y", "z"))
        except (KeyError, TypeError, ValueError):
            return None
        return math.sqrt(x * x + y * y + z * z)

    def matches(self, config: SearchConfig) -> bool:
        checks = (
            (config.star_color, self.star_color, "eq"),
            (config.economy, self.economy, "eq"),
            (config.conflict, self.conflict, "eq"),
            (config.race, self.race, "eq"),
            (config.economy_tier, self.economy_tier, "eq"),
            (config.conflict_tier, self.conflict_tier, "eq"),
            (config.pirate, self.pirate, "eq"),
            (config.abandoned, _flag(self.data.get("abandoned")), "eq"),
            (config.uncharted, _flag(self.data.get("uncharted")), "eq"),
            (config.black_hole, _flag(self.data.get("isBlackHole")), "eq"),
            (config.atlas_system, _flag(self.data.get("isAtlas")), "eq"),
            (config.exact_planets, self.planets, "eq"),
            (config.min_planets, self.planets, "min"),
            (config.min_moons, self.moons, "min"),
            (config.max_moons, self.moons, "max"),
            (config.min_core_distance, self.core_distance, "min"),
            (config.max_core_distance, self.core_distance, "max"),
        )
        for expected, actual, operation in checks:
            if expected is None:
                continue
            if actual is None:
                return False
            if operation == "eq" and isinstance(expected, str):
                if actual != expected.lower():
                    return False
            elif operation == "eq" and actual != expected:
                return False
            elif operation == "min" and actual < expected:
                return False
            elif operation == "max" and actual > expected:
                return False
        return True


# Backwards-compatible name for callers of the early prototype.
SearchResult = SystemRecord
__all__ = ["SystemRecord", "SearchResult"]
